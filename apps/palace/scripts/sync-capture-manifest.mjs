// Copies public/captures/manifest.json into a typed TypeScript const so fixture mode can hang the
// real screenshots without a runtime fetch. Run after regenerating the assets:
//   pnpm --filter @cortex/palace sync-manifest
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const manifest = JSON.parse(readFileSync(join(root, "public", "captures", "manifest.json"), "utf8"));
const entries = manifest.map((e) => ({
  file: e.file,
  app: e.app,
  action: e.action,
  episode: e.episode,
  day: e.day,
  title: e.title,
  listingId: e.listing_id ?? null,
}));
const out = `/**
 * GENERATED by scripts/sync-capture-manifest.mjs from public/captures/manifest.json. Do not edit.
 * Real MockLoft screenshots recorded by tools/play-maya.ts, used by fixture mode as painting textures.
 */
import type { App } from "@cortex/schema";

export interface CaptureManifestEntry {
  file: string;
  app: App;
  action: "load" | "click" | "submit" | "dwell";
  episode: string;
  day: number;
  title: string;
  listingId: string | null;
}

export const CAPTURE_MANIFEST: readonly CaptureManifestEntry[] = ${JSON.stringify(entries, null, 2)};
`;
writeFileSync(join(root, "src", "lib", "fixtures", "captureManifest.ts"), out);
console.log(`captureManifest.ts: ${entries.length} entries`);
